// ป้ายบอกหัวข้อ เช่น "บทที่ 6 · การสร้างใบเสนอราคาใหม่"
export function manualLabel(id: string): string | null {
  const m = /^ch(\d+)(?:-\d+)?$/.exec(id);
  if (!m) return null;
  const title = MANUAL_SECTIONS[id] ?? MANUAL_CHAPTERS[`ch${m[1]}`];
  return title ? `บทที่ ${m[1]} · ${title}` : null;
}

